async function main() {
  let categoriesCreated = 0;
  for (const category of categories) {
    const existing = await prisma.category.findUnique({ where: { slug: category.slug } });
    await prisma.category.upsert({
      where: { slug: category.slug },
      update: {},
      create: category,
    });
    if (!existing) categoriesCreated++;
  }
  console.log(`Categories: ${categoriesCreated} created, ${categories.length - categoriesCreated} already present.`);

  let tagsCreated = 0;
  for (const tag of tags) {
    const existing = await prisma.tag.findUnique({ where: { slug: tag.slug } });
    await prisma.tag.upsert({
      where: { slug: tag.slug },
      update: {},
      create: tag,
    });
    if (!existing) tagsCreated++;
  }
  console.log(`Tags: ${tagsCreated} created, ${tags.length - tagsCreated} already present.`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
